import { spawnSync } from 'node:child_process';
import { chmodSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import type { UAPKGBuildMetadata, UAPKGBuildMode } from '../src/build/BuildMetadata.js';

export const DEVELOPMENT_BANNER_TEXT = 'DEVELOPMENT BUILD';

interface PackageJson {
  readonly version: string;
}

interface SpawnResult {
  readonly status: number | null;
  readonly stdout: string;
  readonly stderr: string;
  readonly error?: Error;
}

export interface CliBuildPaths {
  readonly packageRoot: string;
  readonly distDirectory: string;
  readonly launcherPath: string;
  readonly metadataPath: string;
}

export function resolveCliBuildPaths(
  packageRoot = path.resolve(fileURLToPath(new URL('..', import.meta.url))),
): CliBuildPaths {
  const distDirectory = path.join(packageRoot, 'dist');
  return {
    packageRoot,
    distDirectory,
    launcherPath: path.join(distDirectory, 'cli.js'),
    metadataPath: path.join(distDirectory, 'build', 'BuildMetadata.js'),
  };
}

export function parseBuildMode(args: readonly string[]): UAPKGBuildMode {
  const buildArgs = args.filter((argument) => argument !== '--');
  const supportedFlags = new Set(['--development', '--production']);
  const unknownFlags = buildArgs.filter((argument) => !supportedFlags.has(argument));
  if (unknownFlags.length > 0) {
    throw new Error(`[uapkg-build] Unknown build option(s): ${unknownFlags.join(', ')}`);
  }

  const developmentCount = buildArgs.filter((argument) => argument === '--development').length;
  const productionCount = buildArgs.filter((argument) => argument === '--production').length;

  if (developmentCount > 1 || productionCount > 1) {
    throw new Error('[uapkg-build] Each build mode flag may be provided only once');
  }
  if (developmentCount === 1 && productionCount === 1) {
    throw new Error('[uapkg-build] --development and --production cannot be used together');
  }

  return developmentCount === 1 ? 'development' : 'production';
}

export function createBuildMetadata(mode: UAPKGBuildMode, packageVersion: string): UAPKGBuildMetadata {
  if (packageVersion.trim().length === 0) {
    throw new Error('[uapkg-build] package.json must contain a non-empty version');
  }

  return Object.freeze({
    mode,
    packageVersion,
    displayVersion: mode === 'development' ? `${packageVersion}-development-mode` : packageVersion,
  });
}

export function renderBuildMetadataModule(metadata: UAPKGBuildMetadata): string {
  return [
    '// Generated by build/runCliBuild.ts. Do not edit.',
    `export const UAPKG_BUILD_METADATA = Object.freeze(${JSON.stringify(metadata, null, 2)});`,
    '',
  ].join('\n');
}

export function renderCliLauncher(): string {
  return `#!/usr/bin/env node
import { UAPKG_BUILD_METADATA } from './build/BuildMetadata.js';

if (UAPKG_BUILD_METADATA.mode === 'development') {
  const colorDisabled =
    Object.hasOwn(process.env, 'NO_COLOR') || process.env.FORCE_COLOR === '0';
  const supportsColor =
    !colorDisabled &&
    process.stderr.isTTY === true &&
    (typeof process.stderr.hasColors !== 'function' || process.stderr.hasColors());
  const banner = supportsColor
    ? '\\u001B[44m\\u001B[37m${DEVELOPMENT_BANNER_TEXT}\\u001B[0m'
    : '${DEVELOPMENT_BANNER_TEXT}';
  process.stderr.write(\`\${banner}\\n\`);
}

await import('./cli-bootstrap.js');
`;
}

export function writeBuildArtifacts(paths: CliBuildPaths, metadata: UAPKGBuildMetadata): void {
  mkdirSync(path.dirname(paths.metadataPath), { recursive: true });

  for (const stalePath of [
    path.join(paths.distDirectory, 'cli.d.ts'),
    path.join(paths.distDirectory, 'cli.d.ts.map'),
    path.join(paths.distDirectory, 'cli.js.map'),
    `${paths.metadataPath}.map`,
  ]) {
    rmSync(stalePath, { force: true });
  }

  writeFileSync(paths.metadataPath, renderBuildMetadataModule(metadata), 'utf8');
  writeFileSync(paths.launcherPath, renderCliLauncher(), { encoding: 'utf8', mode: 0o755 });
  chmodSync(paths.launcherPath, 0o755);
}

export function assertBuildMetadata(
  actual: unknown,
  expected: UAPKGBuildMetadata,
): asserts actual is UAPKGBuildMetadata {
  if (
    typeof actual !== 'object' ||
    actual === null ||
    !('mode' in actual) ||
    !('packageVersion' in actual) ||
    !('displayVersion' in actual)
  ) {
    throw new Error('[uapkg-build] Built metadata is missing or malformed');
  }

  const metadata = actual as Record<string, unknown>;
  for (const property of ['mode', 'packageVersion', 'displayVersion'] as const) {
    if (metadata[property] !== expected[property]) {
      throw new Error(
        `[uapkg-build] Expected ${property} ${JSON.stringify(expected[property])}, received ${JSON.stringify(metadata[property])}`,
      );
    }
  }
}

function runBuiltCli(paths: CliBuildPaths): SpawnResult {
  const result = spawnSync(process.execPath, [paths.launcherPath, '--version'], {
    cwd: paths.packageRoot,
    encoding: 'utf8',
    env: {
      ...process.env,
      FORCE_COLOR: '0',
      NO_COLOR: '1',
    },
  });

  return {
    status: result.status,
    stdout: result.stdout ?? '',
    stderr: result.stderr ?? '',
    error: result.error,
  };
}

export async function verifyBuiltCli(paths: CliBuildPaths, expected: UAPKGBuildMetadata): Promise<void> {
  const metadataUrl = pathToFileURL(paths.metadataPath);
  metadataUrl.searchParams.set('verification', `${process.pid}-${Date.now()}-${Math.random()}`);
  const imported = (await import(metadataUrl.href)) as { readonly UAPKG_BUILD_METADATA?: unknown };
  assertBuildMetadata(imported.UAPKG_BUILD_METADATA, expected);

  const result = runBuiltCli(paths);
  if (result.error) {
    throw new Error(`[uapkg-build] Could not execute the built CLI: ${result.error.message}`);
  }
  if (result.status !== 0) {
    throw new Error(`[uapkg-build] Built CLI --version exited with ${String(result.status)}\n${result.stderr}`);
  }

  const expectedStdout = `${expected.displayVersion}\n`;
  if (result.stdout !== expectedStdout) {
    throw new Error(
      `[uapkg-build] Expected --version stdout ${JSON.stringify(expectedStdout)}, received ${JSON.stringify(result.stdout)}`,
    );
  }

  const expectedStderr = expected.mode === 'development' ? `${DEVELOPMENT_BANNER_TEXT}\n` : '';
  if (result.stderr !== expectedStderr) {
    throw new Error(
      `[uapkg-build] Expected --version stderr ${JSON.stringify(expectedStderr)}, received ${JSON.stringify(result.stderr)}`,
    );
  }
}

function readPackageVersion(packageRoot: string): string {
  const packageJson = JSON.parse(readFileSync(path.join(packageRoot, 'package.json'), 'utf8')) as Partial<PackageJson>;
  if (typeof packageJson.version !== 'string') {
    throw new Error('[uapkg-build] package.json must contain a string version');
  }
  return packageJson.version;
}

function runTypeScriptBuild(paths: CliBuildPaths): void {
  const require = createRequire(import.meta.url);
  const tscPath = require.resolve('typescript/bin/tsc');
  const result = spawnSync(process.execPath, [tscPath, '-p', path.join(paths.packageRoot, 'tsconfig.build.json')], {
    cwd: paths.packageRoot,
    stdio: 'inherit',
  });

  if (result.error) {
    throw new Error(`[uapkg-build] Could not start TypeScript: ${result.error.message}`);
  }
  if (result.status !== 0) {
    throw new Error(`[uapkg-build] TypeScript exited with ${String(result.status)}`);
  }
}

export async function buildCli(mode: UAPKGBuildMode, paths = resolveCliBuildPaths()): Promise<UAPKGBuildMetadata> {
  const metadata = createBuildMetadata(mode, readPackageVersion(paths.packageRoot));
  runTypeScriptBuild(paths);
  writeBuildArtifacts(paths, metadata);
  await verifyBuiltCli(paths, metadata);
  return metadata;
}

export async function verifyProductionBuild(paths = resolveCliBuildPaths()): Promise<void> {
  const packageVersion = readPackageVersion(paths.packageRoot);
  await verifyBuiltCli(paths, createBuildMetadata('production', packageVersion));
}
